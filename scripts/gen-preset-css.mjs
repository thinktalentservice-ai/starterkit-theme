#!/usr/bin/env node
/* ═══════════════════════════════════════════════════════════════════════════
   Generates presets/<id>.css — one pre-baked CSS sheet per shipped preset, so a
   consumer can `<link>` a brand's colours without running the engine at request
   time.

   WHY THIS RUNS AGAINST dist/, NOT src/: resolveBrand() and serializeBrandCss()
   are TypeScript source under src/engine/. This repo has no ts-node/tsx-equivalent
   devDependency (checked package.json's devDependencies) to run TS source
   directly from a plain Node script. scripts/smoke.mjs is the one existing
   precedent for a script that consumes this package's OWN code, and its answer
   is: require the COMPILED output, after a build. This script follows the same
   precedent — it imports dist/index.js and dist/presets.js, so it must run
   AFTER `pnpm build`. That is also why, in package.json's `verify` chain,
   `gen:presets:check` sits AFTER `build` rather than beside `gen:tokens:check`
   (which reads a checked-in fixture directly and needs no build at all).

     node scripts/gen-preset-css.mjs            rewrite all 6 presets/<id>.css
     node scripts/gen-preset-css.mjs --check     exit 1 if any is stale (CI)
   ═══════════════════════════════════════════════════════════════════════════ */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const DIST_INDEX = join(ROOT, "dist", "index.js");
const DIST_PRESETS = join(ROOT, "dist", "presets.js");
const OUT_DIR = join(ROOT, "presets");
const CHECK = process.argv.includes("--check");

if (!existsSync(DIST_INDEX) || !existsSync(DIST_PRESETS)) {
  console.error(
    "✗ gen-preset-css: build output missing (dist/index.js, dist/presets.js) — run `pnpm build` first",
  );
  process.exit(1);
}

const { resolveBrand, serializeBrandCss, TOKENS_VERSION } = await import(pathToFileURL(DIST_INDEX).href);
const { PRESETS, PRESET_IDS } = await import(pathToFileURL(DIST_PRESETS).href);

const HEADER = `/* GENERATED by scripts/gen-preset-css.mjs — do not edit.
 * Run \`pnpm gen:presets\`; \`pnpm gen:presets:check\` fails CI when stale.
 *
 * resolveBrand(PRESETS[id]) -> serializeBrandCss(), pre-baked so no engine call
 * is needed at request time. Load alongside styles.css (and bootstrap-bridge.css,
 * if used) — this file defines brand tokens, it does not define structure. */`;

function cssFor(id) {
  const preset = PRESETS[id];
  if (!preset) throw new Error(`no preset registered for id: ${id}`);
  const brand = resolveBrand(preset);
  return serializeBrandCss(brand, {
    header: HEADER,
    provenance: { version: TOKENS_VERSION, brand: id },
  });
}

const generated = new Map(PRESET_IDS.map((id) => [id, cssFor(id)]));

if (CHECK) {
  const stale = [];
  for (const [id, css] of generated) {
    const file = join(OUT_DIR, `${id}.css`);
    const current = existsSync(file) ? readFileSync(file, "utf8").replaceAll(/\r\n/g, "\n") : null;
    if (current !== css) stale.push(id);
  }
  if (stale.length) {
    console.error(`✗ presets/*.css is stale for: ${stale.join(", ")} — run \`pnpm gen:presets\``);
    process.exit(1);
  }
  console.log(`✓ preset CSS up to date (${generated.size} presets)`);
} else {
  if (!existsSync(OUT_DIR)) mkdirSync(OUT_DIR, { recursive: true });
  for (const [id, css] of generated) {
    writeFileSync(join(OUT_DIR, `${id}.css`), css, "utf8");
    console.log(`✓ wrote presets/${id}.css`);
  }
  console.log(`✓ wrote ${generated.size} preset sheets`);
}
